/// Characters (picked separately from the colour). Images: assets/characters/<id>.jpg
/// — generated by .github/workflows/characters.yml (prompts in tool/gen_characters.py).
class Character {
  final String id;
  final String label;
  final bool female;
  final Color hint; // colour used for the placeholder until the image exists
  const Character(this.id, this.label, this.female, this.hint);
  String get asset => 'assets/characters/$id.jpg';
}

